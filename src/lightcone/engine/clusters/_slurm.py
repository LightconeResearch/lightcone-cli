logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Site-keyed SLURM cluster discovery cache (sacctmgr / scontrol output)
# ---------------------------------------------------------------------------


def _cache_path(site: str) -> Path:
    return get_cache_dir() / f"{site}.slurm.yaml"


def load_slurm_cache(site: str) -> Any:
    """Load cached SLURM cluster info (sacctmgr/scontrol) for *site* or ``None``."""
    from lightcone.engine.clusters._slurm_info import cluster_info_from_dict

    path = _cache_path(site)
    if not path.exists():
        return None
    with open(path) as f:
        data = yaml.safe_load(f)
    return cluster_info_from_dict(data) if data else None


def save_slurm_cache(site: str, info: Any) -> Path:
    from lightcone.engine.clusters._slurm_info import cluster_info_to_dict

    path = _cache_path(site)
    with open(path, "w") as f:
        f.write("# AUTO-GENERATED by `lc cluster refresh-cache`. Do not edit.\n")
        yaml.dump(cluster_info_to_dict(info), f, default_flow_style=False, sort_keys=False)
    return path


def is_cache_stale(site: str, max_age_days: int = 30) -> bool:
    path = _cache_path(site)
    if not path.exists():
        return True
    with open(path) as f:
        data = yaml.safe_load(f)
    if not data or not data.get("timestamp"):
        return True
    try:
        ts = datetime.fromisoformat(data["timestamp"])
        return (datetime.now(UTC) - ts).days > max_age_days
    except (ValueError, TypeError):
        return True


def refresh_slurm_cache(site: str) -> Any:
    """Re-query SLURM (sacctmgr/scontrol) and rewrite the cache for *site*."""
    from lightcone.engine.clusters._slurm_info import discover_cluster

    info = discover_cluster()
    save_slurm_cache(site, info)
    return info


