"""SLURM substrate for the cluster abstraction.

Owns everything SLURM-specific: sbatch rendering, ``sbatch``/``squeue``/
``scancel`` lifecycle, QoS preflight against the cluster cache, and
``uv`` worker-env bootstrap.  Public entrypoints take a name + config and
return the same :class:`ClusterInfo` shape every other substrate would.

Future ``_k8s.py`` mirrors this surface.
"""
